'use strict';
// Developer tool (not shipped, not needed to play): regenerates js/vanilla2d.js from a
// QSOLKCB/VANILLAJS checkout. Each ES module is wrapped unchanged in its own function scope so the
// arcade keeps running from file:// with classic deferred scripts. Usage:
//   node scripts/vanilla2d.cjs /path/to/VANILLAJS
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const src=process.argv[2];
if(!src||!fs.existsSync(path.join(src,'modules')))throw new Error('usage: node scripts/vanilla2d.cjs /path/to/VANILLAJS');
let commit='unknown';try{commit=cp.execFileSync('git',['-C',src,'rev-parse','HEAD'],{encoding:'utf8'}).trim();}catch(_){}
const MODULES=['motion2d','range2d','audio2d','ternary-store2d'];
let out=`/* Generated by scripts/vanilla2d.cjs from QSOLKCB/VANILLAJS ${commit}. Do not edit by hand.
 * Modules: ${MODULES.map(m=>'modules/'+m+'/index.js').join(', ')}.
 * Each module body is copied verbatim; only its \`export\` keywords are removed and its exports are
 * published on Arcade.V2D. SPDX-License-Identifier: Apache-2.0 */
(function (A) {
  'use strict';
  const V = A.V2D = {};
`;
for(const name of MODULES){
  const code=fs.readFileSync(path.join(src,'modules',name,'index.js'),'utf8');
  if(/^\s*import\s/m.test(code))throw new Error(name+' imports other modules; extend the generator first');
  const exports=[...code.matchAll(/^export\s+(?:const|function|class)\s+([A-Za-z0-9_$]+)/gm)].map(m=>m[1]);
  const body=code.replace(/^export\s+(const|function|class)\s/gm,'$1 ');
  out+=`  // ---- modules/${name}/index.js\n  Object.assign(V, (function () {\n${body.replace(/^/gm,'    ').replace(/\s+$/,'')}\n    return {${exports.join(', ')}};\n  })());\n`;
}
out+=`  V.source = ${JSON.stringify({repository:'QSOLKCB/VANILLAJS',commit,modules:MODULES})};\n})(globalThis.Arcade);\n`;
fs.writeFileSync(path.join(__dirname,'../js/vanilla2d.js'),out);
console.log('Wrote js/vanilla2d.js from VANILLAJS '+commit+' ('+MODULES.join(', ')+').');
