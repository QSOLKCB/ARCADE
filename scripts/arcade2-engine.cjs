'use strict';
// Reproducible classic-script adapter. Source modules remain byte-for-byte upstream.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..'), vendor = path.join(root, 'arcade2/vendor/vanillajs');
const manifest = JSON.parse(fs.readFileSync(path.join(vendor, 'PROVENANCE.json'), 'utf8'));
let out = `/* Generated by scripts/arcade2-engine.cjs. Do not edit.
 * VANILLAJS ${manifest.version}, commit ${manifest.commit}
 * SPDX-License-Identifier: Apache-2.0 */
(function (A) {
  'use strict';
  A.Engine = {};
`;
for (const name of manifest.modules) {
  const file = 'modules/' + name + '/index.js';
  const code = fs.readFileSync(path.join(vendor, file), 'utf8');
  const hash = crypto.createHash('sha256').update(code).digest('hex');
  if (manifest.sha256[file] !== hash) throw new Error('Upstream bytes changed: ' + file);
  if (/^\s*import\s/m.test(code)) throw new Error('Unresolved import: ' + name);
  const names = [...code.matchAll(/^export\s+(?:const|function|class)\s+([\w$]+)/gm)].map(m => m[1]);
  const body = code.replace(/^export\s+(const|function|class)\s/gm, '$1 ');
  out += `  Object.assign(A.Engine, (function () {\n${body}\nreturn {${names.join(', ')}};\n})());\n`;
}
out += `})(globalThis.Arcade2 = globalThis.Arcade2 || {});\n`;
const target = path.join(root, 'arcade2/engine.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== out) throw new Error('Regenerate arcade2/engine.js');
  console.log('ARCADE2 engine matches pinned VANILLAJS v'+manifest.version+' source: '+manifest.modules.join(', ')+'.');
} else fs.writeFileSync(target, out);
